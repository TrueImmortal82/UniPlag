def main() -> None:
    init_db()
    db = SessionLocal()
    try:
        if not db.query(User).count():
            admin = User(username="admin", role="admin")
            admin.set_password("admin123")
            db.add(admin)
            db.commit()

        if db.query(Document).count():
            print("Демо-данные уже загружены")
            return

        docs = {
            "article": Document(title="Статья о цифровой трансформации", kind="web",
                                url="https://example.edu/digital-edu", domain="example.edu",
                                text=ARTICLE, words=len(ARTICLE.split())),
            "original": Document(title="Курсовая_Иванов_оригинал", author="Иванов И.И.", kind="student",
                                 text=ORIGINAL, words=len(ORIGINAL.split())),
            "copied": Document(title="Реферат_Петрова", author="Петрова А.С.", kind="student",
                               text=COPIED, words=len(COPIED.split())),
            "clean": Document(title="Эссе_Сидоров", author="Сидоров С.С.", kind="student",
                              text=CLEAN, words=len(CLEAN.split())),
        }
        for d in docs.values():
            db.add(d)
        db.commit()
        for d in docs.values():
            db.refresh(d)

        for key in ("article", "original", "clean"):
            check = run_check(db, docs[key])
            print(f"[{key}] plag={check.plag_score}% ai={check.ai_score} method={check.ai_method}")

        target = docs["copied"]
        check = run_check(db, target)
        sources = sorted(check.matches, key=lambda m: -m.sim)
        print(f"[copied] plag={check.plag_score}% ai={check.ai_score}")
        for m in sources:
            print(f"   источник: {m.source_label!r} совпадение {m.sim}%")
        assert check.plag_score > 20, "Плагиат не найден!"
        assert any(m.source_doc_id == docs["article"].id for m in sources), "Веб-источник не найден!"
        assert any(m.source_doc_id == docs["original"].id for m in sources), "Источник-работа не найден!"
        print("OK: демо прошло успешно")
    finally:
        db.close()


if __name__ == "__main__":
    main()
